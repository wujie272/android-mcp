"""MCP Prompts — 模板化工作流定义。

FastMCP 的 `@mcp.prompt()` 注册 Prompt Template，
MCP Client（如 RikkaHub）可调用这些模板快速启动特定工作流。

每个 Prompt 定义：
  - 名称（函数名）
  - 描述（docstring）
  - 参数（可选）
  - 返回的提示文本（由 AI 执行）

参考 us-all/android-mcp-server 的 Prompt 设计思路。
"""

from android_mcp.app import mcp


# ══════════════════════════════════════════════
# Prompt 1: 设备健康检查
# ══════════════════════════════════════════════

@mcp.prompt()
def device_health_check() -> str:
    """检查设备全面健康状况 — 电池、存储、内存、网络、进程一站式诊断。

   适用于：
     - 设备出现卡顿/发热/耗电快时排查问题
     - 定期健康巡检
     - 运行自动化任务前确认设备状态
    """
    return (
        "请对当前手机的**全面健康状况**进行一次诊断。请依次执行以下步骤：\n\n"
        "1. **电池状态** — 调用 get_battery_status() 查看电量、温度、充电状态\n"
        "2. **电池健康** — 调用 get_battery_health() 获取详细电池指标\n"
        "3. **存储信息** — 调用 get_storage_info() 查看存储使用情况\n"
        "4. **网络状态** — 调用 get_wifi_info() 检查 WiFi 连接质量\n"
        "5. **设备信息** — 调用 get_device_info() 查看系统版本、运行时间\n"
        "6. **前台应用** — 调用 get_foreground_app() 查看当前运行的 app\n\n"
        "最后汇总一份**健康报告**，内容包括:\n"
        "- ✅ 正常项\n"
        "- ⚠️ 需要注意的项（如电量低、温度高、存储不足）\n"
        "- ❌ 异常项\n"
        "- 💡 优化建议（如关闭后台应用、清理存储等）"
    )


# ══════════════════════════════════════════════
# Prompt 2: 应用取证分析
# ══════════════════════════════════════════════

@mcp.prompt()
def app_forensic_audit() -> str:
    """对指定 App 进行深度取证分析 — 权限、内存、数据使用、Activity 一览。

   适用于：
     - 怀疑某 App 过度使用权限或耗电
     - 分析 App 启动性能
     - 审计安装的第三方应用
    """
    return (
        "请协助我对一个 App 进行**深度取证分析**。请先问我目标 App 的包名，"
        "然后依次执行以下步骤：\n\n"
        "1. **App 基本信息** — 执行 `dumpsys package <package>` 获取版本、安装时间、UID\n"
        "2. **权限审计** — 列出该 App 持有的所有危险权限（location/camera/contacts/microphone）\n"
        "3. **内存使用** — 执行 `dumpsys meminfo <package>` 分析内存占用\n"
        "4. **Activity 栈** — 查看该 App 的 Activity 信息和启动模式\n"
        "5. **数据使用** — 查看该 App 的数据和缓存大小\n"
        "6. **后台限制** — 检查是否被系统限制后台运行\n\n"
        "最后输出一份**安全审计报告**，标注:\n"
        "- 请求的权限是否合理\n"
        "- 内存占用是否异常\n"
        "- 后台行为是否合规\n"
        "- 安全建议"
    )


# ══════════════════════════════════════════════
# Prompt 3: 屏幕交互与操作
# ══════════════════════════════════════════════

@mcp.prompt()
def screen_interaction_wizard() -> str:
    """全流程屏幕交互向导 — 截图→识别→点击→验证。

   适用于：
     - 自动执行多步骤 UI 操作（如填入表单、翻页、设置调节）
     - 探索性测试 App 界面
     - 自动化重复性操作
    """
    return (
        "你是一个**屏幕操作向导**。我会告诉你我想做什么，你需要:\n\n"
        "1. **理解屏幕** — 调用 dump_ui_with_screenshot() 获取当前画面和可交互元素\n"
        "2. **规划操作** — 根据我的需求确定要点击/输入/滑动的元素\n"
        "3. **执行操作** — 使用 tap_screen() / input_text() / swipe_screen() 执行\n"
        "4. **验证结果** — 再次调用 dump_ui_with_screenshot() 确认操作是否生效\n"
        "5. **继续或结束** — 询问我是否继续下一步操作\n\n"
        "⭐ 规则:\n"
        "  - 每一步都先告诉我你的计划，再执行\n"
        "  - 如果找不到目标元素，就用 dump_ui() 重新获取完整布局\n"
        "  - 操作完成后用一句话告诉我结果\n"
        "  - 如果 3 次尝试都失败，就停下来问我该怎么办"
    )


# ══════════════════════════════════════════════
# Prompt 4: 故障排查助手
# ══════════════════════════════════════════════

@mcp.prompt()
def crash_investigation() -> str:
    """崩溃事故调查 — 拉取日志、分析堆栈、检查权限变更。

   适用于：
     - App 闪退后的故障排查
     - 系统异常（如黑屏、重启）的原因分析
     - 定位最近一次崩溃的根本原因
    """
    return (
        "请协助进行一次**崩溃事故调查**。我将收集诊断信息，请帮我分析。\n\n"
        "请依次执行：\n\n"
        "1. **设备健康基线** — get_battery_status() + get_device_info()\n"
        "2. **前台应用** — get_foreground_app() 确认崩溃时的上下文\n"
        "3. **内存状态** — 如果 ADB/Shizuku 可用，尝试获取 dumpsys meminfo 查看系统内存压力\n"
        "4. **存储状态** — get_storage_info() 检查是否存储空间不足导致异常\n"
        "5. **近期应用变更** — 调用 pm list packages 检查近期安装的 App\n\n"
        "最终输出一份**事故分析报告**:\n"
        "- 📋 设备当时状态\n"
        "- 🔍 可能的原因（内存不足/存储满/权限变更/兼容性问题）\n"
        "- 🛠️ 修复建议（清理缓存/更新应用/恢复出厂设置等）\n"
        "- 💡 预防措施"
    )


# ══════════════════════════════════════════════
# Prompt 5: 自动化操作员
# ══════════════════════════════════════════════

@mcp.prompt()
def automation_operator() -> str:
    """自动化操作员 — 执行预定义的自动化任务流程。

   适用于：
     - 日常重复操作（签到、打卡、领取奖励）
     - 批量处理（如批量删除通知、批量清理缓存）
     - 定时任务（需配合外部调度）
    """
    return (
        "你是一个**自动化操作员**。请帮我执行自动化流程。\n\n"
        "工作模式：\n"
        "1. 我先描述要自动化的任务（如“每天打开 XX App 签到”）\n"
        "2. 你拆解为具体步骤序列\n"
        "3. 你逐个执行，每一步后验证结果\n"
        "4. 完成报告执行结果\n\n"
        "⚠️ 安全规则:\n"
        "  - 操作前先截图让我确认当前页面\n"
        "  - 涉及个人信息输入时先问我\n"
        "  - 每次失败最多重试 2 次\n"
        "  - 如果页面异常跳转，立即停止并报告"
    )
